def _add_code_blocks(slide, code_blocks: list[CodeBlock], theme: Theme) -> None:
    block = code_blocks[0]
    panel = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.75), Inches(1.55), Inches(11.85), Inches(5.18))
    panel.fill.solid()
    panel.fill.fore_color.rgb = RGBColor(15, 23, 42)
    panel.line.color.rgb = theme.accent_color

    label = slide.shapes.add_textbox(Inches(0.95), Inches(1.72), Inches(3.0), Inches(0.28))
    label_frame = label.text_frame
    label_frame.clear()
    p = label_frame.paragraphs[0]
    p.text = block.language.upper()
    run = p.runs[0]
    run.font.size = Pt(10)
    run.font.bold = True
    run.font.name = theme.body_font
    run.font.color.rgb = theme.accent_color

    code_box = slide.shapes.add_textbox(Inches(0.95), Inches(2.1), Inches(11.35), Inches(4.35))
    frame = code_box.text_frame
    frame.word_wrap = True
    frame.clear()

    highlighted_lines = _highlight_code(block.code, block.language)
    for line_index, tokens in enumerate(highlighted_lines[:18]):
        paragraph = frame.paragraphs[0] if line_index == 0 else frame.add_paragraph()
        paragraph.space_after = Pt(0)
        paragraph.line_spacing = 0.9
        if not tokens:
            run = paragraph.add_run()
            run.text = " "
            run.font.size = Pt(12)
            run.font.name = "Consolas"
            continue
        for text, color in tokens:
            run = paragraph.add_run()
            run.text = text
            run.font.size = Pt(12)
            run.font.name = "Consolas"
            run.font.color.rgb = color


def _highlight_code(code: str, language: str) -> list[list[tuple[str, RGBColor]]]:
    try:
        lexer = get_lexer_by_name(language)
    except Exception:
        lexer = TextLexer()

    lines: list[list[tuple[str, RGBColor]]] = [[]]
    for token_type, value in lex(code, lexer):
        color = _token_color(token_type)
        parts = value.split("\n")
        for index, part in enumerate(parts):
            if index:
                lines.append([])
            if part:
                lines[-1].append((part, color))
    return lines


def _token_color(token_type) -> RGBColor:
    if token_type in Keyword or token_type in Name.Builtin:
        return RGBColor(125, 211, 252)
    if token_type in String:
        return RGBColor(134, 239, 172)
    if token_type in Number:
        return RGBColor(253, 186, 116)
    if token_type in Comment:
        return RGBColor(148, 163, 184)
    if token_type in Name.Function or token_type in Name.Class:
        return RGBColor(196, 181, 253)
    return RGBColor(226, 232, 240)


def _diagram_slots(count: int, layout: str) -> list[dict[str, int]]:
    if count <= 1 or layout == "diagram":
        return [{"left": Inches(1.25), "top": Inches(1.65), "width": Inches(10.85), "height": Inches(4.85)}]
    return [
        {"left": Inches(0.9), "top": Inches(1.7), "width": Inches(5.55), "height": Inches(4.7)},
        {"left": Inches(6.9), "top": Inches(1.7), "width": Inches(5.55), "height": Inches(4.7)},
    ]


def _image_slots(count: int, layout: str) -> list[dict[str, int]]:
    if layout == "blueprint":
        return [{"left": Inches(0.65), "top": Inches(1.42), "width": Inches(12.0), "height": Inches(5.25)}]
    if layout == "image-full":
        return [{"left": Inches(0.85), "top": Inches(1.55), "width": Inches(11.65), "height": Inches(4.95)}]
    left = Inches(0.95) if layout == "image-left" else Inches(7.0)
    width = Inches(5.4)
    if count == 1:
        return [{"left": left, "top": Inches(1.7), "width": width, "height": Inches(4.6)}]
    return [
        {"left": left, "top": Inches(1.55), "width": width, "height": Inches(2.3)},
        {"left": left, "top": Inches(4.15), "width": width, "height": Inches(2.3)},
    ]


def _resolve_image_path(image_path: str, base_dir: Path) -> Path:
    path = Path(image_path)
    if path.is_absolute() and path.exists():
        return path

    candidates = [
        base_dir / path,
        base_dir / "images" / path,
        Path.cwd() / path,
        Path.cwd() / "inputs" / path,
        Path.cwd() / "inputs" / "images" / path,
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate

    raise FileNotFoundError(f"Image file not found: {base_dir / path}")


