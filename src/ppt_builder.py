SLIDE_W = Inches(13.333)
SLIDE_H = Inches(7.5)


def build_presentation(
    deck: Deck,
    output_path: Path,
    image_base_dir: Path | None = None,
    theme: Theme | None = None,
    footer_text: str | None = None,
) -> None:
    theme = theme or get_theme(deck.metadata.get("theme"))
    footer_text = footer_text or deck.metadata.get("footer") or "Generated by PPT Generator"
    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H

    _add_title_slide(prs, deck.title, deck.subtitle, theme)
    for slide in deck.slides:
        _add_content_slide(
            prs,
            slide.title,
            slide.body,
            slide.bullets,
            slide.images,
            slide.tables,
            slide.mermaid,
            slide.code_blocks,
            slide.layout,
            image_base_dir or output_path.parent,
            output_path.parent,
            theme,
            footer_text,
        )

    prs.save(output_path)


def _add_title_slide(prs: Presentation, title: str, subtitle: str, theme: Theme) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _add_background(slide, theme.cover_background)
    _add_cover_accents(slide, theme)

    title_box = slide.shapes.add_textbox(Inches(0.9), Inches(2.1), Inches(11.6), Inches(1.0))
    title_frame = title_box.text_frame
    title_frame.clear()
    p = title_frame.paragraphs[0]
    p.text = title
    p.alignment = PP_ALIGN.CENTER
    run = p.runs[0]
    run.font.size = Pt(42)
    run.font.bold = True
    run.font.name = theme.title_font
    run.font.color.rgb = theme.cover_title_color

    subtitle_box = slide.shapes.add_textbox(Inches(2.0), Inches(3.35), Inches(9.3), Inches(0.6))
    subtitle_frame = subtitle_box.text_frame
    subtitle_frame.clear()
    p = subtitle_frame.paragraphs[0]
    p.text = subtitle
    p.alignment = PP_ALIGN.CENTER
    run = p.runs[0]
    run.font.size = Pt(20)
    run.font.name = theme.body_font
    run.font.color.rgb = theme.cover_subtitle_color


def _add_content_slide(
    prs: Presentation,
    title: str,
    body: list[str],
    bullets: list[str],
    images: list[ImageAsset],
    tables: list[Table],
    mermaid: list[MermaidDiagram],
    code_blocks: list[CodeBlock],
    layout: str,
    image_base_dir: Path,
    work_dir: Path,
    theme: Theme,
    footer_text: str,
) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _add_background(slide, theme.slide_background)
    _add_slide_title(slide, title, theme)

    content_layout = _resolve_layout(title, body, bullets, layout, images, tables, mermaid, code_blocks)
    if code_blocks:
        _add_code_blocks(slide, code_blocks, theme)
        _add_footer(slide, footer_text, theme)
        return

    if mermaid:
        _add_mermaid_diagrams(slide, mermaid, work_dir, content_layout, theme)
        _add_footer(slide, footer_text, theme)
        return

    if content_layout in {"image-full", "blueprint"}:
        _add_images(slide, images, image_base_dir, content_layout, theme)
        _add_footer(slide, footer_text, theme)
        return
    if content_layout in {"agenda", "cards", "compare", "timeline", "process", "metrics", "summary", "highlight", "risk", "checklist", "overview"}:
        _add_visual_layout(slide, content_layout, body, bullets, theme)
        _add_footer(slide, footer_text, theme)
        return

    text_left, text_top, text_width, text_height = _text_box_rect(content_layout, bool(tables))
    _add_text_content(slide, body, bullets, text_left, text_top, text_width, text_height, theme)

    if tables:
        table_left, table_top, table_width, table_height = _table_rect(content_layout, bool(body or bullets))
        _add_table(slide, tables[0], table_left, table_top, table_width, table_height, theme)

    if images:
        _add_images(slide, images, image_base_dir, content_layout, theme)

    _add_footer(slide, footer_text, theme)


def _add_slide_title(slide, title: str, theme: Theme) -> None:
    ribbon = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(13.333), Inches(0.16))
    ribbon.fill.solid()
    ribbon.fill.fore_color.rgb = theme.accent_color
    ribbon.line.color.rgb = theme.accent_color

    accent = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.7), Inches(1.25), Inches(1.1), Inches(0.06))
    accent.fill.solid()
    accent.fill.fore_color.rgb = theme.accent_color
    accent.line.color.rgb = theme.accent_color

    title_box = slide.shapes.add_textbox(Inches(0.7), Inches(0.45), Inches(12), Inches(0.7))
    title_frame = title_box.text_frame
    title_frame.clear()
    p = title_frame.paragraphs[0]
    p.text = title
    run = p.runs[0]
    run.font.size = Pt(30)
    run.font.bold = True
    run.font.name = theme.title_font
    run.font.color.rgb = theme.title_color


def _resolve_layout(
    title: str,
    body: list[str],
    bullets: list[str],
    layout: str,
    images: list[ImageAsset],
    tables: list[Table],
    mermaid: list[MermaidDiagram] | None = None,
    code_blocks: list[CodeBlock] | None = None,
) -> str:
    allowed = {
        "auto",
        "text",
        "image-right",
        "image-left",
        "image-full",
        "blueprint",
        "full-table",
        "agenda",
        "cards",
        "compare",
        "timeline",
        "process",
        "metrics",
        "summary",
        "highlight",
        "risk",
        "checklist",
        "overview",
        "diagram",
        "code",
    }
    layout = layout if layout in allowed else "auto"
    if layout != "auto":
        return layout
    if code_blocks:
        return "code"
    if mermaid:
        return "diagram"
    if tables and not images:
        return "full-table"
    if images and not tables:
        return "blueprint" if _looks_like_drawing(title) else ("image-full" if len(images) == 1 else "image-right")
    if images:
        return "image-right"
    return _semantic_layout(title, body, bullets)


def _semantic_layout(title: str, body: list[str], bullets: list[str]) -> str:
    text = " ".join([title, *body[:2], *bullets[:3]])
    if re.search(r"汇报目录|目录|提纲", title):
        return "agenda"
    if re.search(r"汇报重点|重点|结论", title):
        return "highlight"
    if re.search(r"风险|危险|坍塌|触电|打击|伤害|爆炸", text):
        return "risk"
    if re.search(r"流程|进度|计划|程序|步骤|工序", text):
        return "process"
    if re.search(r"职责|措施|保障|应急|验收|标准|管理|控制", text):
        return "checklist"
    if re.search(r"工程概况|工程特性|项目概况|施工部署", text):
        return "overview"
    if len(body) + len(bullets) <= 4:
        return "summary"
    return "text"


def _looks_like_drawing(title: str) -> bool:
    return bool(re.search(r"图|布置|示意|断面|设计|流程|网络|参数", title))


def _text_box_rect(layout: str, has_tables: bool) -> tuple[int, int, int, int]:
    if layout == "image-left":
        return Inches(6.55), Inches(1.55), Inches(5.85), Inches(5.3)
    if layout == "image-right":
        return Inches(0.95), Inches(1.55), Inches(5.8), Inches(5.3)
    if layout == "full-table":
        return Inches(0.95), Inches(1.55), Inches(11.4), Inches(1.0 if has_tables else 5.3)
    return Inches(0.95), Inches(1.55), Inches(11.4), Inches(5.3)


def _table_rect(layout: str, has_text: bool) -> tuple[int, int, int, int]:
    if layout in {"image-left", "image-right"}:
        return Inches(0.95), Inches(3.1 if has_text else 1.7), Inches(5.8), Inches(3.45)
    return Inches(0.95), Inches(2.55 if has_text else 1.7), Inches(11.4), Inches(4.1)


def _add_text_content(slide, body: list[str], bullets: list[str], left: int, top: int, width: int, height: int, theme: Theme) -> None:
    content_box = slide.shapes.add_textbox(left, top, width, height)
    frame = content_box.text_frame
    frame.word_wrap = True
    frame.clear()

    items = [*body, *bullets]
    if not items:
        items = [" "]

    for idx, item in enumerate(items):
        p = frame.paragraphs[0] if idx == 0 else frame.add_paragraph()
        p.text = item
        p.level = 0
        p.space_after = Pt(8)
        run = p.runs[0]
        run.font.size = Pt(21)
        run.font.name = theme.body_font
        run.font.color.rgb = theme.body_color


def _add_visual_layout(slide, layout: str, body: list[str], bullets: list[str], theme: Theme) -> None:
    items = [*body, *bullets] or [" "]
    if layout == "agenda":
        _add_agenda_layout(slide, items, theme)
    elif layout == "cards":
        _add_cards_layout(slide, items, theme)
    elif layout == "compare":
        _add_compare_layout(slide, items, theme)
    elif layout == "timeline":
        _add_timeline_layout(slide, items, theme)
    elif layout == "process":
        _add_process_layout(slide, items, theme)
    elif layout == "metrics":
        _add_metrics_layout(slide, items, theme)
    elif layout == "summary":
        _add_summary_layout(slide, items, theme)
    elif layout == "highlight":
        _add_highlight_layout(slide, items, theme)
    elif layout == "risk":
        _add_risk_layout(slide, items, theme)
    elif layout == "checklist":
        _add_checklist_layout(slide, items, theme)
    elif layout == "overview":
        _add_overview_layout(slide, items, theme)


def _add_agenda_layout(slide, items: list[str], theme: Theme) -> None:
    for index, item in enumerate(_pad_items(items, 5)[:5]):
        top = Inches(1.65 + index * 0.9)
        number = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(1.0), top, Inches(0.62), Inches(0.48))
        number.fill.solid()
        number.fill.fore_color.rgb = theme.accent_color
        number.line.color.rgb = theme.accent_color
        _add_box_text(slide, f"{index + 1}", Inches(1.0), top + Inches(0.06), Inches(0.62), Inches(0.26), theme, Pt(13), bold=True, color=RGBColor(255, 255, 255), align=PP_ALIGN.CENTER)
        _add_box_text(slide, item, Inches(1.85), top - Inches(0.02), Inches(8.6), Inches(0.52), theme, Pt(22), bold=True)
        rule = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(1.85), top + Inches(0.62), Inches(9.6), Inches(0.02))
        rule.fill.solid()
        rule.fill.fore_color.rgb = theme.subtle_fill
        rule.line.color.rgb = theme.subtle_fill


