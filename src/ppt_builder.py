from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

from .markdown_parser import Deck, ImageAsset, Table
from .theme import DEFAULT_THEME, Theme, get_theme


SLIDE_W = Inches(13.333)
SLIDE_H = Inches(7.5)


def build_presentation(
    deck: Deck,
    output_path: Path,
    image_base_dir: Path | None = None,
    theme: Theme | None = None,
    footer_text: str | None = None,
) -> None:
    theme = theme or get_theme(deck.metadata.get("theme"))
    footer_text = footer_text or deck.metadata.get("footer") or "Generated by PPT Generator"
    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H

    _add_title_slide(prs, deck.title, deck.subtitle, theme)
    for slide in deck.slides:
        _add_content_slide(
            prs,
            slide.title,
            slide.body,
            slide.bullets,
            slide.images,
            slide.tables,
            slide.layout,
            image_base_dir or output_path.parent,
            theme,
            footer_text,
        )

    prs.save(output_path)


def _add_title_slide(prs: Presentation, title: str, subtitle: str, theme: Theme) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _add_background(slide, theme.cover_background)
    _add_cover_accents(slide, theme)

    title_box = slide.shapes.add_textbox(Inches(0.9), Inches(2.1), Inches(11.6), Inches(1.0))
    title_frame = title_box.text_frame
    title_frame.clear()
    p = title_frame.paragraphs[0]
    p.text = title
    p.alignment = PP_ALIGN.CENTER
    run = p.runs[0]
    run.font.size = Pt(42)
    run.font.bold = True
    run.font.name = theme.title_font
    run.font.color.rgb = theme.cover_title_color

    subtitle_box = slide.shapes.add_textbox(Inches(2.0), Inches(3.35), Inches(9.3), Inches(0.6))
    subtitle_frame = subtitle_box.text_frame
    subtitle_frame.clear()
    p = subtitle_frame.paragraphs[0]
    p.text = subtitle
    p.alignment = PP_ALIGN.CENTER
    run = p.runs[0]
    run.font.size = Pt(20)
    run.font.name = theme.body_font
    run.font.color.rgb = theme.cover_subtitle_color


def _add_content_slide(
    prs: Presentation,
    title: str,
    body: list[str],
    bullets: list[str],
    images: list[ImageAsset],
    tables: list[Table],
    layout: str,
    image_base_dir: Path,
    theme: Theme,
    footer_text: str,
) -> None:
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _add_background(slide, theme.slide_background)
    _add_slide_title(slide, title, theme)

    content_layout = _resolve_layout(layout, images, tables)
    if content_layout == "image-full":
        _add_images(slide, images, image_base_dir, content_layout, theme)
        _add_footer(slide, footer_text, theme)
        return
    if content_layout in {"cards", "compare", "timeline", "metrics", "summary"}:
        _add_visual_layout(slide, content_layout, body, bullets, theme)
        _add_footer(slide, footer_text, theme)
        return

    text_left, text_top, text_width, text_height = _text_box_rect(content_layout, bool(tables))
    _add_text_content(slide, body, bullets, text_left, text_top, text_width, text_height, theme)

    if tables:
        table_left, table_top, table_width, table_height = _table_rect(content_layout, bool(body or bullets))
        _add_table(slide, tables[0], table_left, table_top, table_width, table_height, theme)

    if images:
        _add_images(slide, images, image_base_dir, content_layout, theme)

    _add_footer(slide, footer_text, theme)


def _add_slide_title(slide, title: str, theme: Theme) -> None:
    ribbon = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(13.333), Inches(0.16))
    ribbon.fill.solid()
    ribbon.fill.fore_color.rgb = theme.accent_color
    ribbon.line.color.rgb = theme.accent_color

    accent = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.7), Inches(1.25), Inches(1.1), Inches(0.06))
    accent.fill.solid()
    accent.fill.fore_color.rgb = theme.accent_color
    accent.line.color.rgb = theme.accent_color

    title_box = slide.shapes.add_textbox(Inches(0.7), Inches(0.45), Inches(12), Inches(0.7))
    title_frame = title_box.text_frame
    title_frame.clear()
    p = title_frame.paragraphs[0]
    p.text = title
    run = p.runs[0]
    run.font.size = Pt(30)
    run.font.bold = True
    run.font.name = theme.title_font
    run.font.color.rgb = theme.title_color


def _resolve_layout(layout: str, images: list[ImageAsset], tables: list[Table]) -> str:
    allowed = {
        "auto",
        "text",
        "image-right",
        "image-left",
        "image-full",
        "full-table",
        "cards",
        "compare",
        "timeline",
        "metrics",
        "summary",
    }
    layout = layout if layout in allowed else "auto"
    if layout != "auto":
        return layout
    if tables and not images:
        return "full-table"
    if images and not tables:
        return "image-full" if len(images) == 1 else "image-right"
    if images:
        return "image-right"
    return "text"


def _text_box_rect(layout: str, has_tables: bool) -> tuple[int, int, int, int]:
    if layout == "image-left":
        return Inches(6.55), Inches(1.55), Inches(5.85), Inches(5.3)
    if layout == "image-right":
        return Inches(0.95), Inches(1.55), Inches(5.8), Inches(5.3)
    if layout == "full-table":
        return Inches(0.95), Inches(1.55), Inches(11.4), Inches(1.0 if has_tables else 5.3)
    return Inches(0.95), Inches(1.55), Inches(11.4), Inches(5.3)


def _table_rect(layout: str, has_text: bool) -> tuple[int, int, int, int]:
    if layout in {"image-left", "image-right"}:
        return Inches(0.95), Inches(3.1 if has_text else 1.7), Inches(5.8), Inches(3.45)
    return Inches(0.95), Inches(2.55 if has_text else 1.7), Inches(11.4), Inches(4.1)


def _add_text_content(slide, body: list[str], bullets: list[str], left: int, top: int, width: int, height: int, theme: Theme) -> None:
    content_box = slide.shapes.add_textbox(left, top, width, height)
    frame = content_box.text_frame
    frame.word_wrap = True
    frame.clear()

    items = [*body, *bullets]
    if not items:
        items = [" "]

    for idx, item in enumerate(items):
        p = frame.paragraphs[0] if idx == 0 else frame.add_paragraph()
        p.text = item
        p.level = 0
        p.space_after = Pt(8)
        run = p.runs[0]
        run.font.size = Pt(21)
        run.font.name = theme.body_font
        run.font.color.rgb = theme.body_color


def _add_visual_layout(slide, layout: str, body: list[str], bullets: list[str], theme: Theme) -> None:
    items = [*body, *bullets] or [" "]
    if layout == "cards":
        _add_cards_layout(slide, items, theme)
    elif layout == "compare":
        _add_compare_layout(slide, items, theme)
    elif layout == "timeline":
        _add_timeline_layout(slide, items, theme)
    elif layout == "metrics":
        _add_metrics_layout(slide, items, theme)
    elif layout == "summary":
        _add_summary_layout(slide, items, theme)


def _add_cards_layout(slide, items: list[str], theme: Theme) -> None:
    lefts = [Inches(0.8), Inches(4.65), Inches(8.5)]
    for index, item in enumerate(_pad_items(items, 3)[:3]):
        panel = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, lefts[index], Inches(1.75), Inches(3.25), Inches(4.55))
        panel.fill.solid()
        panel.fill.fore_color.rgb = theme.subtle_fill
        panel.line.color.rgb = theme.accent_color
        _add_box_text(
            slide,
            f"{index + 1:02d}",
            lefts[index] + Inches(0.25),
            Inches(2.05),
            Inches(0.8),
            Inches(0.42),
            theme,
            Pt(18),
            bold=True,
            color=theme.accent_color,
        )
        _add_box_text(slide, item, lefts[index] + Inches(0.25), Inches(2.8), Inches(2.75), Inches(2.4), theme, Pt(20), bold=True)


def _add_compare_layout(slide, items: list[str], theme: Theme) -> None:
    groups = _split_items(items, 2)
    labels = ["方案 A", "方案 B"]
    lefts = [Inches(0.9), Inches(6.85)]
    for index, group in enumerate(groups):
        panel = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, lefts[index], Inches(1.7), Inches(5.45), Inches(4.75))
        panel.fill.solid()
        panel.fill.fore_color.rgb = theme.subtle_fill
        panel.line.color.rgb = theme.accent_color if index == 0 else theme.table_header
        _add_box_text(slide, labels[index], lefts[index] + Inches(0.25), Inches(1.95), Inches(4.9), Inches(0.5), theme, Pt(22), bold=True, color=theme.title_color)
        _add_box_text(slide, "\n".join(f"- {item}" for item in group), lefts[index] + Inches(0.35), Inches(2.8), Inches(4.75), Inches(2.9), theme, Pt(17))


def _add_timeline_layout(slide, items: list[str], theme: Theme) -> None:
    visible = _pad_items(items, 4)[:4]
    line = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(1.2), Inches(3.58), Inches(10.9), Inches(0.05))
    line.fill.solid()
    line.fill.fore_color.rgb = theme.accent_color
    line.line.color.rgb = theme.accent_color
    for index, item in enumerate(visible):
        x = Inches(1.25 + index * 2.85)
        marker = slide.shapes.add_shape(MSO_SHAPE.OVAL, x, Inches(3.25), Inches(0.65), Inches(0.65))
        marker.fill.solid()
        marker.fill.fore_color.rgb = theme.accent_color
        marker.line.color.rgb = theme.accent_color
        _add_box_text(slide, str(index + 1), x, Inches(3.38), Inches(0.65), Inches(0.3), theme, Pt(13), bold=True, color=RGBColor(255, 255, 255), align=PP_ALIGN.CENTER)
        _add_box_text(slide, item, x - Inches(0.55), Inches(4.25), Inches(1.75), Inches(1.3), theme, Pt(15), bold=True, align=PP_ALIGN.CENTER)


def _add_metrics_layout(slide, items: list[str], theme: Theme) -> None:
    positions = [
        (Inches(0.9), Inches(1.8)),
        (Inches(6.8), Inches(1.8)),
        (Inches(0.9), Inches(4.15)),
        (Inches(6.8), Inches(4.15)),
    ]
    for index, item in enumerate(_pad_items(items, 4)[:4]):
        value, label = _split_metric(item)
        left, top = positions[index]
        panel = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, left, top, Inches(5.45), Inches(1.65))
        panel.fill.solid()
        panel.fill.fore_color.rgb = theme.subtle_fill
        panel.line.color.rgb = theme.accent_color
        _add_box_text(slide, value, left + Inches(0.28), top + Inches(0.22), Inches(4.9), Inches(0.55), theme, Pt(27), bold=True, color=theme.accent_color)
        _add_box_text(slide, label, left + Inches(0.3), top + Inches(0.95), Inches(4.8), Inches(0.42), theme, Pt(15), color=theme.body_color)


def _add_summary_layout(slide, items: list[str], theme: Theme) -> None:
    for index, item in enumerate(items[:6]):
        top = Inches(1.65 + index * 0.75)
        badge = slide.shapes.add_shape(MSO_SHAPE.OVAL, Inches(1.0), top, Inches(0.34), Inches(0.34))
        badge.fill.solid()
        badge.fill.fore_color.rgb = theme.accent_color
        badge.line.color.rgb = theme.accent_color
        _add_box_text(slide, item, Inches(1.55), top - Inches(0.03), Inches(10.3), Inches(0.48), theme, Pt(19), bold=index == 0)


def _add_box_text(
    slide,
    text: str,
    left: int,
    top: int,
    width: int,
    height: int,
    theme: Theme,
    size: Pt,
    bold: bool = False,
    color: RGBColor | None = None,
    align=PP_ALIGN.LEFT,
) -> None:
    box = slide.shapes.add_textbox(left, top, width, height)
    frame = box.text_frame
    frame.word_wrap = True
    frame.clear()
    p = frame.paragraphs[0]
    p.text = text
    p.alignment = align
    run = p.runs[0]
    run.font.size = size
    run.font.bold = bold
    run.font.name = theme.body_font
    run.font.color.rgb = color or theme.body_color


def _pad_items(items: list[str], count: int) -> list[str]:
    padded = items[:]
    while len(padded) < count:
        padded.append("待补充")
    return padded


def _split_items(items: list[str], groups: int) -> list[list[str]]:
    midpoint = max(1, (len(items) + groups - 1) // groups)
    return [items[index * midpoint : (index + 1) * midpoint] or ["待补充"] for index in range(groups)]


def _split_metric(item: str) -> tuple[str, str]:
    for separator in [":", "：", "|"]:
        if separator in item:
            first, second = item.split(separator, 1)
            return first.strip(), second.strip()
    parts = item.split(maxsplit=1)
    if len(parts) == 2:
        return parts[0], parts[1]
    return item, "指标说明"


def _add_table(slide, table_data: Table, left: int, top: int, width: int, height: int, theme: Theme) -> None:
    row_count = len(table_data.rows) + 1
    col_count = len(table_data.headers)
    table_shape = slide.shapes.add_table(row_count, col_count, left, top, width, height)
    table = table_shape.table

    for col_idx, header in enumerate(table_data.headers):
        _set_cell(table.cell(0, col_idx), header, theme, is_header=True)

    for row_idx, row in enumerate(table_data.rows, start=1):
        for col_idx, value in enumerate(row):
            _set_cell(table.cell(row_idx, col_idx), value, theme, is_header=False)


def _set_cell(cell, text: str, theme: Theme, is_header: bool) -> None:
    cell.text = text
    cell.margin_left = Inches(0.06)
    cell.margin_right = Inches(0.06)
    cell.margin_top = Inches(0.04)
    cell.margin_bottom = Inches(0.04)

    fill = cell.fill
    fill.solid()
    fill.fore_color.rgb = theme.table_header if is_header else RGBColor(255, 255, 255)

    for paragraph in cell.text_frame.paragraphs:
        paragraph.alignment = PP_ALIGN.CENTER
        for run in paragraph.runs:
            run.font.name = theme.body_font
            run.font.size = Pt(12 if is_header else 11)
            run.font.bold = is_header
            run.font.color.rgb = RGBColor(255, 255, 255) if is_header else theme.body_color


def _add_footer(slide, footer_text: str, theme: Theme) -> None:
    footer = slide.shapes.add_textbox(Inches(0.7), Inches(7.0), Inches(12), Inches(0.3))
    footer_frame = footer.text_frame
    footer_frame.clear()
    p = footer_frame.paragraphs[0]
    p.text = footer_text
    p.alignment = PP_ALIGN.RIGHT
    run = p.runs[0]
    run.font.size = Pt(10)
    run.font.name = theme.body_font
    run.font.color.rgb = theme.footer_color


def _add_background(slide, color: RGBColor) -> None:
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _add_images(slide, images: list[ImageAsset], base_dir: Path, layout: str, theme: Theme) -> None:
    slots = _image_slots(len(images), layout)
    for image, slot in zip(images, slots):
        _add_image_panel(slide, slot, theme)
        image_path = _resolve_image_path(image.path, base_dir)
        picture = slide.shapes.add_picture(str(image_path), slot["left"], slot["top"])
        _fit_picture(picture, slot["width"], slot["height"])
        picture.left = slot["left"] + int((slot["width"] - picture.width) / 2)
        picture.top = slot["top"] + int((slot["height"] - picture.height) / 2)

        if image.alt:
            caption = slide.shapes.add_textbox(
                slot["left"],
                slot["top"] + slot["height"] + Inches(0.08),
                slot["width"],
                Inches(0.25),
            )
            frame = caption.text_frame
            frame.clear()
            p = frame.paragraphs[0]
            p.text = image.alt
            p.alignment = PP_ALIGN.CENTER
            run = p.runs[0]
            run.font.size = Pt(10)
            run.font.color.rgb = RGBColor(100, 116, 139)


def _image_slots(count: int, layout: str) -> list[dict[str, int]]:
    if layout == "image-full":
        return [{"left": Inches(0.85), "top": Inches(1.55), "width": Inches(11.65), "height": Inches(4.95)}]
    left = Inches(0.95) if layout == "image-left" else Inches(7.0)
    width = Inches(5.4)
    if count == 1:
        return [{"left": left, "top": Inches(1.7), "width": width, "height": Inches(4.6)}]
    return [
        {"left": left, "top": Inches(1.55), "width": width, "height": Inches(2.3)},
        {"left": left, "top": Inches(4.15), "width": width, "height": Inches(2.3)},
    ]


def _resolve_image_path(image_path: str, base_dir: Path) -> Path:
    path = Path(image_path)
    if path.is_absolute() and path.exists():
        return path

    candidates = [
        base_dir / path,
        base_dir / "images" / path,
        Path.cwd() / path,
        Path.cwd() / "inputs" / path,
        Path.cwd() / "inputs" / "images" / path,
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate

    raise FileNotFoundError(f"Image file not found: {base_dir / path}")


def _add_cover_accents(slide, theme: Theme) -> None:
    top_bar = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(13.333), Inches(0.18))
    top_bar.fill.solid()
    top_bar.fill.fore_color.rgb = theme.accent_color
    top_bar.line.color.rgb = theme.accent_color

    block = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.65), Inches(5.85), Inches(2.1), Inches(0.16))
    block.fill.solid()
    block.fill.fore_color.rgb = theme.accent_color
    block.line.color.rgb = theme.accent_color


def _add_image_panel(slide, slot: dict[str, int], theme: Theme) -> None:
    panel = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE,
        slot["left"] - Inches(0.08),
        slot["top"] - Inches(0.08),
        slot["width"] + Inches(0.16),
        slot["height"] + Inches(0.16),
    )
    panel.fill.solid()
    panel.fill.fore_color.rgb = theme.subtle_fill
    panel.line.color.rgb = theme.accent_color


def _fit_picture(picture, max_width: int, max_height: int) -> None:
    width_ratio = max_width / picture.width
    height_ratio = max_height / picture.height
    ratio = min(width_ratio, height_ratio)
    picture.width = int(picture.width * ratio)
    picture.height = int(picture.height * ratio)
